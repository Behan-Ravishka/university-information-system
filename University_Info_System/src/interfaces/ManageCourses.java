    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        DefaultTableModel model = (DefaultTableModel) coursesjTable.getModel();
        Connection conn = DBManager.getConnection();

        try {
            for (int i = 0; i < model.getRowCount(); i++) {
                Object idObj = model.getValueAt(i, 0);
                String name = model.getValueAt(i, 1).toString();
                int credits = Integer.parseInt(model.getValueAt(i, 2).toString());
                String deptName = model.getValueAt(i, 3).toString();
                String info = model.getValueAt(i, 4).toString();

                // Get department ID from department name
                int deptId = -1;
                String getDeptIdSQL = "SELECT Id FROM Academic_Department WHERE Name = ?";
                PreparedStatement deptStmt = conn.prepareStatement(getDeptIdSQL);
                deptStmt.setString(1, deptName);
                ResultSet deptRs = deptStmt.executeQuery();
                if (deptRs.next()) {
                    deptId = deptRs.getInt("Id");
                } else {
                    JOptionPane.showMessageDialog(this, "Department '" + deptName + "' not found.");
                    continue;
                }
                deptStmt.close();

                if (idObj == null || idObj.toString().isEmpty()) {
                    // Insert new course
                    String insertSQL = "INSERT INTO Course_Modules (Name, Credits, Info, Department_Id) VALUES (?, ?, ?, ?)";
                    PreparedStatement insertStmt = conn.prepareStatement(insertSQL);
                    insertStmt.setString(1, name);
                    insertStmt.setInt(2, credits);
                    insertStmt.setString(3, info);
                    insertStmt.setInt(4, deptId);
                    insertStmt.executeUpdate();
                    insertStmt.close();
                } else {
                    // Update existing course
                    int id = Integer.parseInt(idObj.toString());
                    String updateSQL = "UPDATE Course_Modules SET Name=?, Credits=?, Info=?, Department_Id=? WHERE Id=?";
                    PreparedStatement updateStmt = conn.prepareStatement(updateSQL);
                    updateStmt.setString(1, name);
                    updateStmt.setInt(2, credits);
                    updateStmt.setString(3, info);
                    updateStmt.setInt(4, deptId);
                    updateStmt.setInt(5, id);
                    updateStmt.executeUpdate();
                    updateStmt.close();
                }
            }
            JOptionPane.showMessageDialog(this, "Courses saved successfully!");
            loadCourseDetails(); // Refresh the table
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error saving courses: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_saveBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        int selectedRow = coursesjTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a course to delete.");
            return;
        }

        DefaultTableModel model = (DefaultTableModel) coursesjTable.getModel();
        Object idObj = model.getValueAt(selectedRow, 0);

        if (idObj == null || idObj.toString().isEmpty()) {
            // Just remove the new row from table
            model.removeRow(selectedRow);
        } else {
            int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this course?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                try {
                    int id = Integer.parseInt(idObj.toString());
                    Connection conn = DBManager.getConnection();
                    String deleteSQL = "DELETE FROM Course_Modules WHERE Id=?";
                    PreparedStatement deleteStmt = conn.prepareStatement(deleteSQL);
                    deleteStmt.setInt(1, id);
                    deleteStmt.executeUpdate();
                    deleteStmt.close();

                    model.removeRow(selectedRow);
                    JOptionPane.showMessageDialog(this, "Course deleted successfully.");
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Error deleting course: " + e.getMessage());
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_deleteBtnActionPerformed

