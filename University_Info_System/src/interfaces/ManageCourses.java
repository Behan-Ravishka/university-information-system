    private void loadCourseDetails() {
        Connection conn = null;
        PreparedStatement stmt = null;
        ResultSet rs = null;

        try {
            conn = database.DBManager.getConnection();
            String sql = "SELECT c.Id, c.Name, c.Credits, c.Info, d.Name AS DepartmentName "
                    + "FROM Course_Modules c "
                    + "JOIN Academic_Department d ON c.Department_Id = d.Id";

            stmt = conn.prepareStatement(sql);
            rs = stmt.executeQuery();

            String[] columnNames = {"Course ID", "Course Name", "Credits", "Department", "Info"};
            DefaultTableModel model = new DefaultTableModel(columnNames, 0);

            while (rs.next()) {
                Object[] row = {
                    rs.getInt("Id"),
                    rs.getString("Name"),
                    rs.getInt("Credits"),
                    rs.getString("DepartmentName"),
                    rs.getString("Info") != null ? rs.getString("Info") : "N/A"
                };
                model.addRow(row);
            }
            coursesjTable.setModel(model);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading course details: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (stmt != null) {
                    stmt.close();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }

