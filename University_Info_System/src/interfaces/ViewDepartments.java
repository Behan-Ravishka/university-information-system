    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        DefaultTableModel model = (DefaultTableModel) DepartmentsDetailsjTable.getModel();
    Connection conn = DBManager.getConnection();

    try {
        for (int i = 0; i < model.getRowCount(); i++) {
            Object idObj = model.getValueAt(i, 0);
            String name = (String) model.getValueAt(i, 1);
            int noPrograms = Integer.parseInt(model.getValueAt(i, 2).toString());
            String email = (String) model.getValueAt(i, 3);
            String phone = (String) model.getValueAt(i, 4);

            if (idObj == null || idObj.toString().isEmpty()) {
                String insertSQL = "INSERT INTO Academic_Department (Name, No_of_Programs, ContactEmail, ContactPhone) VALUES (?, ?, ?, ?)";
                PreparedStatement insertStmt = conn.prepareStatement(insertSQL);
                insertStmt.setString(1, name);
                insertStmt.setInt(2, noPrograms);
                insertStmt.setString(3, email);
                insertStmt.setString(4, phone);
                insertStmt.executeUpdate();
                insertStmt.close();
            } else {
                int id = Integer.parseInt(idObj.toString());
                String updateSQL = "UPDATE Academic_Department SET Name=?, No_of_Programs=?, ContactEmail=?, ContactPhone=? WHERE Id=?";
                PreparedStatement updateStmt = conn.prepareStatement(updateSQL);
                updateStmt.setString(1, name);
                updateStmt.setInt(2, noPrograms);
                updateStmt.setString(3, email);
                updateStmt.setString(4, phone);
                updateStmt.setInt(5, id);
                updateStmt.executeUpdate();
                updateStmt.close();
            }
        }
        JOptionPane.showMessageDialog(this, "Data saved successfully!");
        displayDepartments();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error saving data: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_saveBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        int selectedRow = DepartmentsDetailsjTable.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a row to delete.");
        return;
    }

    DefaultTableModel model = (DefaultTableModel) DepartmentsDetailsjTable.getModel();
    Object idObj = model.getValueAt(selectedRow, 0);

    if (idObj == null || idObj.toString().isEmpty()) {
        model.removeRow(selectedRow);
    } else {
        int id = Integer.parseInt(idObj.toString());
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this department?", "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = DBManager.getConnection();
                String deleteSQL = "DELETE FROM Academic_Department WHERE Id=?";
                PreparedStatement deleteStmt = conn.prepareStatement(deleteSQL);
                deleteStmt.setInt(1, id);
                deleteStmt.executeUpdate();
                deleteStmt.close();

                model.removeRow(selectedRow);
                JOptionPane.showMessageDialog(this, "Department deleted successfully.");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error deleting data: " + e.getMessage());
                e.printStackTrace();
            }
        }
    }
    }//GEN-LAST:event_deleteBtnActionPerformed

