    private void displayDepartments() {
        Connection conn = database.DBManager.getConnection();
        String query = "SELECT * FROM Academic_Department";

        try (PreparedStatement stmt = conn.prepareStatement(query); ResultSet rs = stmt.executeQuery()) {

            String[] columnNames = {"ID", "Name", "Programs", "Email", "Phone"};

            DefaultTableModel model = new DefaultTableModel(columnNames, 0);

            while (rs.next()) {
                int id = rs.getInt("Id");
                String name = rs.getString("Name");
                int noPrograms = rs.getInt("No_of_Programs");
                String email = rs.getString("ContactEmail");
                String phone = rs.getString("ContactPhone");

                Object[] row = {id, name, noPrograms, email, phone};
                model.addRow(row);
            }

            DepartmentsDetailsjTable.setModel(model);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading departments: " + e.getMessage());
            e.printStackTrace();
        }
    }

