    private void loadStudentDetails() {
        Connection conn = null;
        Statement stmt = null;
        ResultSet rs = null;

        try {
            conn = database.DBManager.getConnection();
            stmt = conn.createStatement();
            String query = "SELECT Id, Name, Phone_No, Gender, Email, Address, DateOfBirth, Intake, Degree_Name FROM Student";
            rs = stmt.executeQuery(query);

            String[] columnNames = {"ID", "Name", "Phone No", "Gender", "Email", "Address", "DOB", "Intake", "Degree"};
            DefaultTableModel model = new DefaultTableModel(columnNames, 0);

            while (rs.next()) {
                Object[] row = {
                    rs.getInt("Id"),
                    rs.getString("Name"),
                    rs.getString("Phone_No"),
                    rs.getString("Gender"),
                    rs.getString("Email"),
                    rs.getString("Address"),
                    rs.getDate("DateOfBirth"),
                    rs.getInt("Intake"),
                    rs.getString("Degree_Name")
                };
                model.addRow(row);
            }

            StudentsDetailsjTable.setModel(model);

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading student details.", "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (stmt != null) {
                    stmt.close();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }

