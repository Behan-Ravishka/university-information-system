    private void EditStudentsDetailsBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditStudentsDetailsBtnActionPerformed
        int selectedRow = StudentsDetailsjTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row to edit.", "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Get updated values from the selected row
        int id = (int) StudentsDetailsjTable.getValueAt(selectedRow, 0);
        String name = StudentsDetailsjTable.getValueAt(selectedRow, 1).toString();
        String phone = StudentsDetailsjTable.getValueAt(selectedRow, 2).toString();
        String gender = StudentsDetailsjTable.getValueAt(selectedRow, 3).toString();
        String email = StudentsDetailsjTable.getValueAt(selectedRow, 4).toString();
        String address = StudentsDetailsjTable.getValueAt(selectedRow, 5).toString();
        java.util.Date dob = (java.util.Date) StudentsDetailsjTable.getValueAt(selectedRow, 6);
        int intake = Integer.parseInt(StudentsDetailsjTable.getValueAt(selectedRow, 7).toString());
        String degree = StudentsDetailsjTable.getValueAt(selectedRow, 8).toString();

        Connection conn = null;
        PreparedStatement pstmt = null;

        try {
            conn = database.DBManager.getConnection();
            String updateQuery = "UPDATE Student SET Name = ?, Phone_No = ?, Gender = ?, Email = ?, Address = ?, DateOfBirth = ?, Intake = ?, Degree_Name = ? WHERE Id = ?";
            pstmt = conn.prepareStatement(updateQuery);

            pstmt.setString(1, name);
            pstmt.setString(2, phone);
            pstmt.setString(3, gender);
            pstmt.setString(4, email);
            pstmt.setString(5, address);
            pstmt.setDate(6, new java.sql.Date(dob.getTime()));
            pstmt.setInt(7, intake);
            pstmt.setString(8, degree);
            pstmt.setInt(9, id);

            int rowsAffected = pstmt.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Student details updated successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Update failed. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error updating student details.", "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (pstmt != null) {
                    pstmt.close();
                }
                if (conn != null) {
                    conn.close();
                }
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_EditStudentsDetailsBtnActionPerformed

