    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        int selectedRow = LecturerDetailsjTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row to delete.", "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete the selected lecturer?", "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        int id = (int) LecturerDetailsjTable.getValueAt(selectedRow, 0);

        Connection conn = null;
        PreparedStatement pstmt = null;

        try {
            conn = database.DBManager.getConnection();
            String deleteQuery = "DELETE FROM Lecturer WHERE Id = ?";
            pstmt = conn.prepareStatement(deleteQuery);
            pstmt.setInt(1, id);

            int rowsAffected = pstmt.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Lecturer deleted successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);

                // Remove row from table
                DefaultTableModel model = (DefaultTableModel) LecturerDetailsjTable.getModel();
                model.removeRow(selectedRow);
            } else {
                JOptionPane.showMessageDialog(this, "Delete failed. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error deleting lecturer: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (pstmt != null) {
                    pstmt.close();
                }
                if (conn != null) {
                    conn.close();
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_deleteBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        int selectedRow = LecturerDetailsjTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row to update.", "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Retrieve updated values from the table
        int id = (int) LecturerDetailsjTable.getValueAt(selectedRow, 0);
        String name = LecturerDetailsjTable.getValueAt(selectedRow, 1).toString();
        String gender = LecturerDetailsjTable.getValueAt(selectedRow, 2).toString();
        String email = LecturerDetailsjTable.getValueAt(selectedRow, 3).toString();
        int departmentId = Integer.parseInt(LecturerDetailsjTable.getValueAt(selectedRow, 4).toString());
        String degrees = LecturerDetailsjTable.getValueAt(selectedRow, 5).toString();

        Connection conn = null;
        PreparedStatement pstmt = null;

        try {
            conn = database.DBManager.getConnection();
            String updateQuery = "UPDATE Lecturer SET Name = ?, Gender = ?, Email = ?, Department_Id = ?, Degrees = ? WHERE Id = ?";
            pstmt = conn.prepareStatement(updateQuery);

            pstmt.setString(1, name);
            pstmt.setString(2, gender);
            pstmt.setString(3, email);
            pstmt.setInt(4, departmentId);
            pstmt.setString(5, degrees);
            pstmt.setInt(6, id);

            int rowsAffected = pstmt.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Lecturer details updated successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Update failed. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error updating lecturer details: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (pstmt != null) {
                    pstmt.close();
                }
                if (conn != null) {
                    conn.close();
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_updateBtnActionPerformed

