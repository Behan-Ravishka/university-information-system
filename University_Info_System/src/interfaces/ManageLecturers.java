    private void displayLecturerData() {
        Connection conn = null;
        Statement stmt = null;
        ResultSet rs = null;

        try {
            conn = database.DBManager.getConnection();
            stmt = conn.createStatement();
            String query = "SELECT * FROM Lecturer";
            rs = stmt.executeQuery(query);

            String[] columnNames = {"ID", "Name", "Gender", "Email", "Department ID", "Degrees"};
            DefaultTableModel model = new DefaultTableModel(columnNames, 0);

            while (rs.next()) {
                Object[] row = {
                    rs.getInt("Id"),
                    rs.getString("Name"),
                    rs.getString("Gender"),
                    rs.getString("Email"),
                    rs.getInt("Department_Id"),
                    rs.getString("Degrees")
                };
                model.addRow(row);
            }

            LecturerDetailsjTable.setModel(model);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading lecturer data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (stmt != null) {
                    stmt.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }
    }

