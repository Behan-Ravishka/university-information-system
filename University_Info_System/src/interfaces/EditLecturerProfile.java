    private void updatebtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updatebtnActionPerformed
        try (Connection conn = database.DBManager.getConnection()) {
            // Fetch the current password if the user hasn't updated it
            String currentPassword = null;

            // Query to get the current password from the database
            String getPasswordQuery = "SELECT Password FROM Lecturer WHERE Id = ?";
            try (PreparedStatement getPasswordStmt = conn.prepareStatement(getPasswordQuery)) {
                getPasswordStmt.setInt(1, Integer.parseInt(lecturerId));
                try (ResultSet passwordResult = getPasswordStmt.executeQuery()) {
                    if (passwordResult.next()) {
                        currentPassword = passwordResult.getString("Password");
                    }
                }
            }

            // If password field is empty, use the current password
            String updatedPassword = new String(LecturerPasswordField.getPassword());
            if (updatedPassword.isEmpty()) {
                updatedPassword = currentPassword;
            }

            // SQL Query to update the lecturer details
            String query = "UPDATE Lecturer SET Name = ?, Gender = ?, Email = ?, Degrees = ?, Department_Id = (SELECT Id FROM Academic_Department WHERE Name = ?), Password = ? WHERE Id = ?";
            try (PreparedStatement stmt = conn.prepareStatement(query)) {
                String updatedName = name.getText();
                String updatedGender = (String) LecturerGenderjComboBox.getSelectedItem(); // Get selected gender
                String updatedEmail = email.getText();
                String updatedDegrees = degrees.getText();
                String updatedDepartment = (String) LecturerDepartmentjComboBox.getSelectedItem();

                // Set parameters for the update query
                stmt.setString(1, updatedName);
                stmt.setString(2, updatedGender); // Set the selected gender
                stmt.setString(3, updatedEmail);
                stmt.setString(4, updatedDegrees);
                stmt.setString(5, updatedDepartment);
                stmt.setString(6, updatedPassword); // Set the updated password (or the current one)
                stmt.setInt(7, Integer.parseInt(lecturerId));

                // Execute the update
                int rowsAffected = stmt.executeUpdate();
                if (rowsAffected > 0) {
                    JOptionPane.showMessageDialog(this, "Lecturer profile updated successfully!");
                    loadLecturerData(); // Refresh data
                } else {
                    JOptionPane.showMessageDialog(this, "Update failed. Please try again.");
                }
            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "An error occurred while updating the profile.");
        }
    }//GEN-LAST:event_updatebtnActionPerformed

