    private void loadLecturerData() {
        try (Connection conn = database.DBManager.getConnection()) {
            String query = "SELECT l.Id, l.Name, l.Gender, l.Email, l.Degrees, a.Name as DepartmentName "
                    + "FROM Lecturer l "
                    + "JOIN Academic_Department a ON l.Department_Id = a.Id "
                    + "WHERE l.Id = ?";
            try (PreparedStatement stmt = conn.prepareStatement(query)) {
                stmt.setInt(1, Integer.parseInt(lecturerId));
                try (ResultSet rs = stmt.executeQuery()) {
                    if (rs.next()) {
                        id.setText(rs.getString("Id"));
                        name.setText(rs.getString("Name"));
                        String gender = rs.getString("Gender");
                        if (gender != null) {
                            LecturerGenderjComboBox.setSelectedItem(gender); // Set gender in combo box
                        }
                        email.setText(rs.getString("Email"));
                        degrees.setText(rs.getString("Degrees"));
                        LecturerDepartmentjComboBox.setSelectedItem(rs.getString("DepartmentName"));
                    }
                }
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Failed to load lecturer data.");
        }
    }
