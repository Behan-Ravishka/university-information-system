    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        int selectedRow = assistantLecturersjTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row to delete.", "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete the selected assistant lecturer?", "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        int id = (int) assistantLecturersjTable.getValueAt(selectedRow, 0); // Get Assistant Lecturer ID from column 0

        Connection conn = null;
        PreparedStatement pstmt = null;

        try {
            conn = database.DBManager.getConnection();
            String deleteQuery = "DELETE FROM Lecturer_Assistant WHERE Id = ?";
            pstmt = conn.prepareStatement(deleteQuery);
            pstmt.setInt(1, id);

            int rowsAffected = pstmt.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Assistant Lecturer deleted successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);

                // Remove row from table
                DefaultTableModel model = (DefaultTableModel) assistantLecturersjTable.getModel();
                model.removeRow(selectedRow);
            } else {
                JOptionPane.showMessageDialog(this, "Delete failed. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error deleting assistant lecturer: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (pstmt != null) {
                    pstmt.close();
                }
                if (conn != null) {
                    conn.close();
                }
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_deleteBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        int selectedRow = assistantLecturersjTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row to update.", "No Selection", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int id = (int) assistantLecturersjTable.getValueAt(selectedRow, 0); // ID
        String name = assistantLecturersjTable.getValueAt(selectedRow, 1).toString();
        String email = assistantLecturersjTable.getValueAt(selectedRow, 2).toString();
        String lecturerName = assistantLecturersjTable.getValueAt(selectedRow, 3).toString();
        String departmentName = assistantLecturersjTable.getValueAt(selectedRow, 4).toString();

        Connection conn = null;
        PreparedStatement pstmt = null;
        ResultSet rs = null;

        try {
            conn = database.DBManager.getConnection();

            // Get Lecturer_Id from Lecturer_Name
            String getLecturerIdQuery = "SELECT Id FROM Lecturer WHERE Name = ?";
            pstmt = conn.prepareStatement(getLecturerIdQuery);
            pstmt.setString(1, lecturerName);
            rs = pstmt.executeQuery();
            int lecturerId = rs.next() ? rs.getInt("Id") : -1;
            rs.close();
            pstmt.close();

            if (lecturerId == -1) {
                throw new SQLException("Invalid Lecturer Name");
            }

            // Get Department_Id from Department_Name
            String getDepartmentIdQuery = "SELECT Id FROM Academic_Department WHERE Name = ?";
            pstmt = conn.prepareStatement(getDepartmentIdQuery);
            pstmt.setString(1, departmentName);
            rs = pstmt.executeQuery();
            int departmentId = rs.next() ? rs.getInt("Id") : -1;
            rs.close();
            pstmt.close();

            if (departmentId == -1) {
                throw new SQLException("Invalid Department Name");
            }

            // Perform update
            String updateQuery = "UPDATE Lecturer_Assistant SET Name = ?, Email = ?, Lecturer_Id = ?, Department_Id = ? WHERE Id = ?";
            pstmt = conn.prepareStatement(updateQuery);
            pstmt.setString(1, name);
            pstmt.setString(2, email);
            pstmt.setInt(3, lecturerId);
            pstmt.setInt(4, departmentId);
            pstmt.setInt(5, id);

            int rowsAffected = pstmt.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Assistant Lecturer details updated successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Update failed. Please try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error updating assistant lecturer: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (pstmt != null) {
                    pstmt.close();
                }
                if (conn != null) {
                    conn.close();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }//GEN-LAST:event_updateBtnActionPerformed

