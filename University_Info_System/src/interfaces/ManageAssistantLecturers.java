    private void displayAssistantLecturerDetails() {
        Connection conn = null;
        PreparedStatement stmt = null;
        ResultSet rs = null;

        try {
            conn = database.DBManager.getConnection();
            String sql = "SELECT la.Id, la.Name, la.Email, l.Name AS Lecturer_Name, d.Name AS Department_Name "
                    + "FROM Lecturer_Assistant la "
                    + "JOIN Lecturer l ON la.Lecturer_Id = l.Id "
                    + "JOIN Academic_Department d ON la.Department_Id = d.Id";

            stmt = conn.prepareStatement(sql);
            rs = stmt.executeQuery();

            String[] columnNames = {"ID", "Name", "Email", "Lecturer In-Charge", "Department"};
            DefaultTableModel model = new DefaultTableModel(columnNames, 0);

            while (rs.next()) {
                Object[] row = {
                    rs.getInt("Id"),
                    rs.getString("Name"),
                    rs.getString("Email"),
                    rs.getString("Lecturer_Name"),
                    rs.getString("Department_Name")
                };
                model.addRow(row);
            }

            assistantLecturersjTable.setModel(model);

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading assistant lecturer data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (stmt != null) {
                    stmt.close();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }

